"""تطبيع النص العربي للبحث. يجب أن يطابق تنفيذ Dart لاحقاً (المرحلة 5) حرفياً.

القواعد (محافظة عمداً):
  1) حذف التشكيل وعلامات التلاوة: U+0610-061A, U+064B-065F, U+0670, U+06D6-06ED
  2) حذف التطويل U+0640
  3) توحيد الألف: أ إ آ ٱ -> ا
  4) توحيد الياء المقصورة: ى -> ي
  5) تحويل الأرقام العربية-الهندية إلى غربية
النص المعروض للمستخدم لا يُعدَّل أبداً؛ التطبيع للعمود search فقط.
"""
import re

_STRIP = re.compile("[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")
_MAP = str.maketrans({
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا", "ى": "ي",
    **{chr(0x0660 + i): str(i) for i in range(10)},
    **{chr(0x06F0 + i): str(i) for i in range(10)},
})


def normalize_ar(text: str) -> str:
    text = _STRIP.sub("", text)
    text = text.translate(_MAP)
    return re.sub(r"\s+", " ", text).strip()
